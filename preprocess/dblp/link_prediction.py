"""Build a homogeneous-flat DHN bundle for DBLP paper-venue link prediction.

Mirrors Bishwash's MAGNN-LP graph construction (KC_scripts/MAGNN/paper-venue.py /
preprocess_DBLP{1,2}.py) so the graph content matches the baseline, then flattens
the author/paper/term/conf/area heterograph to a single homogeneous PyG Data with
the scalable DHN pattern set {p1, c2}.

Task: paper <-> conf (predict a paper's venue). Three topology variants:
  - v1 (area-paper) : edges P-A (all), P-T (all), P-C (TRAIN only), P-R (paper-area)
  - v2 (area-venue) : edges P-A (all), P-T (all), P-C (TRAIN only), C-R (conf-area)
  - v3 (area-author): edges P-A (all), P-T (all), P-C (TRAIN only), A-R (author-area)
  - universal (DBLP*): common edges plus P-R, C-R, and A-R

Leakage prevention by construction: only TRAIN paper-conf positives enter the
graph; val/test target edges are never added. Area edges (P-R / C-R / A-R) are
auxiliary structural context (area is not the LP target), so they use all
available labels regardless of split.

Negatives are a FLAT POOL (M, 2) of (paper, conf) pairs, not a (N, K) grid --
this matches the DBLP runner, which samples neg_mult per batch at train time
and subsamples <=3 per paper at test time.

`x` is None: the trainer creates nn.Embedding(num_nodes, in_dim) for no-feature
parity with the baseline.

Splits come from data/preprocessed/DBLP_shared_splits/DBLP_pc_shared_splits.npz
(generated by preprocess.dblp.shared_splits). Run that first. The split
generator defaults to the full eligible paper set.

Usage:
    python -m preprocess.dblp.link_prediction --variant v1
    python -m preprocess.dblp.link_prediction --variant v1,v2,v3
    python -m preprocess.dblp.link_prediction --variant universal
"""
from __future__ import annotations

import argparse
import os
import random
import sys
from pathlib import Path

import numpy as np
import pandas as pd
import torch
import networkx as nx
from torch_geometric.data import Data

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from dhn.graph_enumerations import (  # noqa: E402
    cycle_mapping_index,
    single_node_mapping_index,
)

SEED = 1566911444
MIN_CONF = 0
PATTERNS = ["p1", "c2"]

PATTERN_FNS = {
    "p1": lambda g: single_node_mapping_index(g),
    "c2": lambda g: cycle_mapping_index(g, length_bound=2),
}


def set_seed(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)


# ---- Load + filter raw tables (mirror paper-venue.py steps 1-4) ------------

def load_filtered(raw_dir: str, paper_subset: np.ndarray):
    """Replicate the baseline's filtering + the exact paper_subset, then build
    per-type id maps. Returns (pa, pt, pc, pr, ar, maps, counts)."""
    al = pd.read_csv(os.path.join(raw_dir, "author_label.txt"), sep="\t",
                     names=["author_id", "label", "name"], header=None, encoding="utf-8")
    pa = pd.read_csv(os.path.join(raw_dir, "paper_author.txt"), sep="\t",
                     names=["paper_id", "author_id"], header=None, encoding="utf-8")
    pc = pd.read_csv(os.path.join(raw_dir, "paper_conf.txt"), sep="\t",
                     names=["paper_id", "conf_id"], header=None, encoding="utf-8")
    pt = pd.read_csv(os.path.join(raw_dir, "paper_term.txt"), sep="\t",
                     names=["paper_id", "term_id"], header=None, encoding="utf-8")

    valid_authors = set(al["author_id"])
    pa = pa[pa["author_id"].isin(valid_authors)].reset_index(drop=True)
    valid_papers = set(pa["paper_id"])
    pc = pc[pc["paper_id"].isin(valid_papers)].reset_index(drop=True)
    pt = pt[pt["paper_id"].isin(valid_papers)].reset_index(drop=True)
    pa = pa[pa["paper_id"].isin(valid_papers)].reset_index(drop=True)
    big_confs = pc["conf_id"].value_counts().loc[lambda x: x >= MIN_CONF].index
    pc = pc[pc["conf_id"].isin(big_confs)].reset_index(drop=True)
    valid_papers = set(pc["paper_id"])
    pa = pa[pa["paper_id"].isin(valid_papers)].reset_index(drop=True)
    pt = pt[pt["paper_id"].isin(valid_papers)].reset_index(drop=True)

    # Enforce the exact paper subset used to make the splits.
    keep = set(paper_subset.tolist()) & valid_papers
    pa = pa[pa["paper_id"].isin(keep)].reset_index(drop=True)
    pc = pc[pc["paper_id"].isin(keep)].reset_index(drop=True)
    pt = pt[pt["paper_id"].isin(keep)].reset_index(drop=True)
    valid_papers = set(pc["paper_id"])

    # paper -> area via author labels (auxiliary; uses all papers, area != target)
    a2r = al.set_index("author_id")["label"]
    pr = (pa.assign(area_id=pa["author_id"].map(a2r))
          [["paper_id", "area_id"]].drop_duplicates().dropna().reset_index(drop=True))
    pr["area_id"] = pr["area_id"].astype(np.int64)
    ar = (al[["author_id", "label"]].rename(columns={"label": "area_id"})
          .drop_duplicates().dropna().reset_index(drop=True))
    ar["area_id"] = ar["area_id"].astype(np.int64)

    Au_ids = sorted(al["author_id"].unique())
    Pa_ids = sorted(valid_papers)
    Te_ids = sorted(pt["term_id"].unique())
    Co_ids = sorted(pc["conf_id"].unique())
    Ar_ids = sorted(set(pr["area_id"].unique()) | set(ar["area_id"].unique()))
    maps = {
        "author": {a: i for i, a in enumerate(Au_ids)},
        "paper": {p: i for i, p in enumerate(Pa_ids)},
        "term": {t: i for i, t in enumerate(Te_ids)},
        "conf": {c: i for i, c in enumerate(Co_ids)},
        "area": {r: i for i, r in enumerate(Ar_ids)},
    }
    counts = {k: len(v) for k, v in maps.items()}
    return pa, pt, pc, pr, ar, maps, counts


def map_pairs(arr, Pmap, Cmap):
    """Map raw (paper, conf) pairs to local ids; drop any not present."""
    if len(arr) == 0:
        return np.empty((0, 2), dtype=np.int64)
    df = pd.DataFrame(arr, columns=["paper_id", "conf_id"])
    df["paper_id"] = df["paper_id"].map(Pmap)
    df["conf_id"] = df["conf_id"].map(Cmap)
    return df.dropna().to_numpy(dtype=np.int64)


# ---- Edge construction -----------------------------------------------------

def _add(d: dict, key: str, u: int, v: int) -> None:
    if key not in d:
        d[key] = ([], [])
    d[key][0].append(int(u))
    d[key][1].append(int(v))


def build_typed_edges(variant, pa, pt, pc, pr, ar, train_pos_local, maps):
    """Local-id typed edges. P-C is TRAIN-only; area edges are auxiliary (all)."""
    raw: dict = {}
    Au, Pa, Te, Co, Ar = (maps["author"], maps["paper"], maps["term"],
                          maps["conf"], maps["area"])

    # P-A (all)
    for p, a in pa[["paper_id", "author_id"]].itertuples(index=False):
        if p in Pa and a in Au:
            _add(raw, "paper-author", Pa[p], Au[a])
    # P-T (all)
    for p, t in pt[["paper_id", "term_id"]].itertuples(index=False):
        if p in Pa and t in Te:
            _add(raw, "paper-term", Pa[p], Te[t])
    # P-C (TRAIN ONLY) -- the target relation
    for p_local, c_local in train_pos_local:
        _add(raw, "paper-conf", int(p_local), int(c_local))

    if variant in {"v1", "universal"}:
        # P-R (paper-area)
        for p, r in pr[["paper_id", "area_id"]].itertuples(index=False):
            if p in Pa and r in Ar:
                _add(raw, "paper-area", Pa[p], Ar[r])
    if variant in {"v2", "universal"}:
        # C-R (conf-area) must be derived from TRAIN target edges only. Using
        # held-out P-C rows here would leak validation/test venue assignments.
        train_pc = pd.DataFrame(
            train_pos_local, columns=["paper_local", "conf_local"]
        )
        pr_local = pr[["paper_id", "area_id"]].copy()
        pr_local["paper_local"] = pr_local["paper_id"].map(Pa)
        pr_local["area_local"] = pr_local["area_id"].map(Ar)
        cr = (
            train_pc.merge(
                pr_local[["paper_local", "area_local"]].dropna(),
                on="paper_local",
            )[["conf_local", "area_local"]]
            .drop_duplicates()
            .astype(np.int64)
        )
        for c_local, r_local in cr.itertuples(index=False):
            _add(raw, "conf-area", c_local, r_local)
    if variant in {"v3", "universal"}:
        # A-R (author-area): direct author labels from author_label.txt
        for a, r in ar[["author_id", "area_id"]].itertuples(index=False):
            if a in Au and r in Ar:
                _add(raw, "author-area", Au[a], Ar[r])
    if variant not in {"v1", "v2", "v3", "universal"}:
        raise ValueError(
            f"variant must be v1, v2, v3, or universal, got {variant}"
        )
    return raw


def flatten_to_global(typed_edges: dict, offsets: dict) -> torch.Tensor:
    """{'paper-author': ([u_locals],[v_locals]), ...} -> global edge_index
    (2, 2E) with reverse edges added (PyG undirected convention)."""
    src_chunks, dst_chunks = [], []
    for rel_key, (u_locals, v_locals) in typed_edges.items():
        if not u_locals:
            continue
        u_type, v_type = rel_key.split("-")
        if u_type not in offsets or v_type not in offsets:
            raise ValueError(f"Unknown node type(s) in relation {rel_key!r}; offsets has {list(offsets)}")
        u = np.asarray(u_locals, dtype=np.int64) + offsets[u_type]
        v = np.asarray(v_locals, dtype=np.int64) + offsets[v_type]
        src_chunks.append(u)
        dst_chunks.append(v)
    src = np.concatenate(src_chunks)
    dst = np.concatenate(dst_chunks)
    src_all = np.concatenate([src, dst])
    dst_all = np.concatenate([dst, src])
    return torch.from_numpy(np.vstack([src_all, dst_all]))


# ---- Main per-variant preprocessing ---------------------------------------

def preprocess_one(
    raw_dir,
    shared_npz,
    variant,
    out_path,
    seed,
    allow_partial_paper_subset=False,
):
    set_seed(seed)
    print(f"\n=== DBLP DHN-LP preprocess | task=pc variant={variant} ===", flush=True)

    z = np.load(shared_npz)
    paper_subset = z["paper_subset"]
    paper_keep_frac = (
        float(z["paper_keep_frac"]) if "paper_keep_frac" in z.files else None
    )
    if not allow_partial_paper_subset:
        if paper_keep_frac is None:
            raise ValueError(
                "Split file has no paper_keep_frac metadata and may be the old "
                "10% artifact. Regenerate it with "
                "`python -m preprocess.dblp.shared_splits`."
            )
        if paper_keep_frac != 1.0:
            raise ValueError(
                f"Split file retains only {100.0 * paper_keep_frac:.1f}% of "
                "eligible papers. Regenerate the full split or pass "
                "--allow-partial-paper-subset for an explicitly labelled "
                "scalability study."
            )
    pa, pt, pc, pr, ar, maps, counts = load_filtered(raw_dir, paper_subset)
    A, P, T, C, R = (counts["author"], counts["paper"], counts["term"],
                     counts["conf"], counts["area"])

    # Global offsets: author -> paper -> term -> conf -> area
    offsets = {"author": 0, "paper": A, "term": A + P, "conf": A + P + T,
               "area": A + P + T + C}
    num_nodes_total = A + P + T + C + R

    train_pos_l = map_pairs(z["train_pos"], maps["paper"], maps["conf"])
    val_pos_l = map_pairs(z["val_pos"], maps["paper"], maps["conf"])
    test_pos_l = map_pairs(z["test_pos"], maps["paper"], maps["conf"])
    train_neg_l = map_pairs(z["train_neg"], maps["paper"], maps["conf"])
    val_neg_l = map_pairs(z["val_neg"], maps["paper"], maps["conf"])
    test_neg_l = map_pairs(z["test_neg"], maps["paper"], maps["conf"])

    print(f"  Counts: authors={A} papers={P} terms={T} confs={C} areas={R}")
    print(f"  Total nodes: {num_nodes_total}")
    print(f"  Pos: train={len(train_pos_l)} val={len(val_pos_l)} test={len(test_pos_l)}")
    print(f"  Neg pool: train={len(train_neg_l)} val={len(val_neg_l)} test={len(test_neg_l)}")

    typed_edges = build_typed_edges(variant, pa, pt, pc, pr, ar, train_pos_l, maps)
    print("  Typed edge counts:")
    for k, (u, _) in typed_edges.items():
        print(f"    {k:<14s} {len(u)}")

    edge_index = flatten_to_global(typed_edges, offsets)
    print(f"  Flat edge_index: {tuple(edge_index.shape)} (includes reverse direction)")

    print("  Building NetworkX graph (undirected, deduped)...")
    nxg = nx.Graph()
    nxg.add_nodes_from(range(num_nodes_total))
    seen = set()
    for i, j in zip(edge_index[0].tolist(), edge_index[1].tolist()):
        if i == j:
            continue
        seen.add((i, j) if i < j else (j, i))
    nxg.add_edges_from(sorted(seen))
    print(f"    edges (undirected, deduped): {nxg.number_of_edges()}")

    print(f"  Enumerating patterns {PATTERNS}...")
    mapping_index_dict = {}
    for p in PATTERNS:
        mapping_index_dict.update(PATTERN_FNS[p](nxg))
    for k, v in mapping_index_dict.items():
        print(f"    {k}: {None if v is None else tuple(v.shape)}")

    # Splits -> global ids. head = paper, target = conf.
    poff, coff = offsets["paper"], offsets["conf"]

    def pos_to_global(pos):
        out = np.empty_like(pos)
        out[:, 0] = pos[:, 0] + poff
        out[:, 1] = pos[:, 1] + coff
        return torch.from_numpy(out).long()

    splits = {
        "train_pos": pos_to_global(train_pos_l),
        "val_pos": pos_to_global(val_pos_l),
        "test_pos": pos_to_global(test_pos_l),
        "train_neg": pos_to_global(train_neg_l),
        "val_neg": pos_to_global(val_neg_l),
        "test_neg": pos_to_global(test_neg_l),
    }

    data = Data(x=None, edge_index=edge_index, mapping_index_dict=mapping_index_dict)
    data.num_nodes = num_nodes_total
    data.batch = torch.zeros(num_nodes_total, dtype=torch.long)
    data.batch_size = 1

    bundle = {
        "data": data,
        "splits": splits,
        "node_offsets": offsets,
        "meta": {
            "task": "pc",
            "variant": variant,
            "mapping_mode": "invariant_union_graph" if variant == "universal" else "baseline",
            "union_of_variants": ["v1", "v2", "v3"] if variant == "universal" else None,
            "head_type": "paper",
            "target_type": "conf",
            "neg_format": "flat_pool",  # (M, 2) pairs, not (N, K)
            "num_nodes_per_type": counts,
            "num_nodes_total": num_nodes_total,
            "kendall_keys": ["paper_id", "conf_id"],
            "patterns": PATTERNS,
            "paper_keep_frac": paper_keep_frac,
        },
    }

    os.makedirs(os.path.dirname(out_path) or ".", exist_ok=True)
    torch.save(bundle, out_path)
    print(f"  Saved bundle -> {out_path}")


def _parse_variants(s):
    vals = [x.strip().lower() for x in str(s).split(",") if x.strip()]
    bad = [v for v in vals if v not in {"v1", "v2", "v3", "universal"}]
    if bad:
        raise SystemExit(
            f"Unknown variant(s): {bad}; expected v1, v2, v3, and/or universal"
        )
    return vals


def main():
    ap = argparse.ArgumentParser(description="DBLP DHN-LP preprocessing (homogeneous-flat).")
    ap.add_argument(
        "--variant",
        default="v1",
        help=(
            "Comma-separated: v1 (area-paper), v2 (area-venue), "
            "v3 (area-author), universal (all three area relations)."
        ),
    )
    ap.add_argument("--raw-dir", default="data/raw/DBLP")
    ap.add_argument("--shared-npz",
                    default="data/preprocessed/DBLP_shared_splits/DBLP_pc_shared_splits.npz")
    ap.add_argument("--out-dir", default="data/preprocessed")
    ap.add_argument("--seed", type=int, default=SEED)
    ap.add_argument(
        "--allow-partial-paper-subset",
        action="store_true",
        help="Allow a split artifact whose paper_keep_frac is below 1.0.",
    )
    args = ap.parse_args()

    if not Path(args.shared_npz).is_file():
        raise SystemExit(f"Missing shared npz: {args.shared_npz}\n"
                         f"Run python -m preprocess.dblp.shared_splits first.")

    for v in _parse_variants(args.variant):
        out_path = f"{args.out_dir}/DBLP_dhn_lp_pc_{v}.pt"
        preprocess_one(
            args.raw_dir,
            args.shared_npz,
            v,
            out_path,
            args.seed,
            args.allow_partial_paper_subset,
        )


if __name__ == "__main__":
    main()
